def apply():
    from russian_pack import BASE,read,write,validate,mask,key
    scope=read(BASE/'scope.json');path=BASE/'translations.json';draft=read(path)
    changed=0
    for job in scope['jobs']:
        assert job['id']==key(job['source'],job['max_utf8_bytes'])
        value=OVERRIDES.get((job['source'],job['max_utf8_bytes']),ID_OVERRIDES.get(job['id']))
        if value is None:continue
        checked,reason=validate(job,mask(value)[0])
        assert reason is None,(job,value,reason)
        value=checked
        draft['entries'][job['id']]=dict(source=job['source'],translation=value,
            max_utf8_bytes=job['max_utf8_bytes'],status='compact_ui_reviewed')
        draft['rejected'].pop(job['id'],None);changed+=1
    write(path,draft);print('Applied compact Russian UI labels:',changed)

if __name__=='__main__':apply()
