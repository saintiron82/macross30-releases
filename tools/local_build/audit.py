"""Inspect actual release archives; fail closed on complete or generated game code."""
import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import zipfile

from source_bundle import allowed

ROOT = Path(__file__).resolve().parents[2]
RUNTIME = {'runtime/bin/ffmpeg/' + name for name in
           ('avutil-61.dll', 'avcodec-63.dll', 'avformat-63.dll', 'swresample-7.dll')}
RUNTIME.add('runtime/THIRD-PARTY-NOTICES.txt')
TEXT_DATA = {'payload/Macross30.cmd', 'payload/CollectLogs.cmd', 'payload/DistInstaller.cs',
             'payload/recipe.json', 'payload/battle-captions.json',
             'payload/plans/ko-KR.tsv', 'payload/plans/ja-JP.tsv',
             'payload/launch-tools/launch-helper.ps1', 'payload/launch-tools/collect-logs.ps1',
             'payload/korean/data-version.txt', 'payload/korean/install-plan.tsv', 'payload/korean/korean-pack.json'}


def inspect(directory, manifest, original=None):
    if set(manifest['files']) != {'source', 'data', 'third_party'}:
        raise ValueError('Exactly three reviewed artifact kinds required')
    report = {'passed': False, 'version': manifest['version'], 'archives': [],
              'complete_game_executables': 0, 'generated_game_sources': 0,
              'original_byte_array_scan': original is not None}
    for kind, row in manifest['files'].items():
        path = Path(directory) / row['file']
        archive_bytes = path.read_bytes()
        if len(archive_bytes) != row['bytes'] or hashlib.sha256(archive_bytes).hexdigest() != row['sha256']:
            raise ValueError('Archive identity mismatch: ' + path.name)
        names = set()
        with zipfile.ZipFile(path) as archive:
            for entry in archive.infolist():
                name = entry.filename
                parts = PurePosixPath(name).parts
                if name in names or '\\' in name or '..' in parts or name.startswith('/') or entry.is_dir():
                    raise ValueError('Invalid archive path: ' + name)
                names.add(name)
                data = archive.read(entry)
                if kind == 'source':
                    if not name.startswith('source/') or (name != 'source/source-manifest.json' and not allowed(name[7:])):
                        raise ValueError('Unreviewed source path: ' + name)
                    if data.startswith((b'MZ', b'\x7fELF', b'SCE\0', b'!<arch>')):
                        raise ValueError('Executable/object disguised as source: ' + name)
                    text = data.decode('utf8')
                    independent_stub = name == 'source/vendor/ps3recomp-master/runtime/spu/spu_tsp_weak.c' and hashlib.sha256(data.replace(b'\r\n', b'\n')).hexdigest() == '65143ebc6a9fb0cfa7ced7118218477343a07e697b06ceefab1be0d946ff3579'
                    if not independent_stub and Path(name).suffix in ('.c', '.cpp', '.h', '.inc') and re.search(
                            r'Auto-generated by (?:spu|ppu)_lifter|Generated exactoriginalcode|void (?:func_[0-9A-F]{8}|\w+_spu_func_[0-9A-F]{8})\([^;]*\)\s*\{', text):
                        raise ValueError('Generated game code: ' + name)
                    # Developer audit: detect literal original-code byte arrays even in unrelated headers.
                    # Recipes contain offsets and hashes; literal original arrays must be generated locally.
                    if original is not None:
                        for match in re.finditer(r'(?<![\w])(?:0x[\da-fA-F]+|\d+)[uUlL]*(?:\s*,\s*(?:0x[\da-fA-F]+|\d+)[uUlL]*){63,}', text):
                            values = [int(token.rstrip('uUlL'), 16 if token.lower().startswith('0x') else 10)
                                      for token in re.split(r'\s*,\s*', match[0])]
                            if max(values) <= 255 and bytes(values) in original:
                                raise ValueError('Original byte array in source: ' + name)
                elif kind == 'data':
                    delta = (name.startswith('payload/korean/') or name == 'payload/elf/ko-KR.mkdelta') and name.endswith('.mkdelta')
                    subtitle = name.startswith('payload/subtitles/') and Path(name).suffix in ('.srt', '.tsv')
                    if delta:
                        if not data.startswith(b'MKDELTA1'):
                            raise ValueError('Invalid patch format: ' + name)
                    elif name in TEXT_DATA or subtitle:
                        data.decode('utf8')
                        if data.startswith((b'MZ', b'\x7fELF', b'SCE\0')):
                            raise ValueError('Executable disguised as data: ' + name)
                    else:
                        raise ValueError('Unlisted data payload: ' + name)
                elif kind == 'third_party':
                    if name not in RUNTIME:
                        raise ValueError('Unlisted runtime file: ' + name)
                else:
                    raise ValueError('Unknown package kind')
            if kind == 'third_party' and names != RUNTIME:
                raise ValueError('Incomplete runtime package')
        report['archives'].append(dict(file=path.name, bytes=len(archive_bytes), sha256=row['sha256'], entries=len(names)))
    report['passed'] = True
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', type=Path)
    parser.add_argument('--original-elf', type=Path)
    args = parser.parse_args()
    manifest = json.loads((args.directory / 'LOCAL-BUILD.json').read_text(encoding='utf8'))
    report = inspect(args.directory, manifest, args.original_elf.read_bytes() if args.original_elf else None)
    (args.directory / 'PUBLIC-PACKAGE-AUDIT.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf8')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
