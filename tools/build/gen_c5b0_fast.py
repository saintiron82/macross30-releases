"""Rewrite geom1's C5B0 body so SPU registers live in host locals.

The lifted body reads and writes every SPU register through ctx->gpr[N], and
every local-store store goes through a byte pointer, so the compiler must
assume each LS store may change any register and reloads them all. Here the
registers become locals (R0..R127): loaded once on entry, spilled to ctx only
around the two calls into the 88E0 helper and before the tail exit, reloaded
after the calls. LS accesses use direct big-endian loads/stores without the
debug probe hooks (probes are diagnostics only).

Semantics are unchanged; verify with `python tools/diag/fast_verdict.py cpu`, which
compares LS, GPRs and context bit-exactly against eight real captures.

usage: python tools/build/gen_c5b0_fast.py   (idempotent; reads the .bak original)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'native/macross30/spu_gameplay/geom1/spu_recomp.c'
ORIG = SRC.with_name('spu_recomp.c.bak-20261024')
NAME = 'macross_geom1_c5b0_original_body'


def extract(text, name):
    m = re.search(r'static void ' + name + r'\(spu_context\* ctx\) \{', text)
    i, depth = m.end(), 1
    while depth:
        c = text[i]
        depth += c == '{'
        depth -= c == '}'
        i += 1
    return m.start(), i


def main():
    original = ORIG.read_text(encoding='utf-8')
    a, b = extract(original, NAME)
    func = original[a:b]
    nl = '\r\n' if '\r\n' in func else '\n'
    header_end = func.index('{') + 1
    body = func[header_end:-1]

    regs = sorted({int(n) for n in re.findall(r'ctx->gpr\[(\d+)\]', body)})
    body = re.sub(r'ctx->gpr\[(\d+)\]', r'R\1', body)
    body = body.replace('spu_ls_read128(ctx, ', 'C5_LSR(').replace('spu_ls_write128(ctx, ', 'C5_LSW(')
    calls = body.count('macross_geom1_spu_func_000088E0(ctx);')
    body = body.replace('macross_geom1_spu_func_000088E0(ctx);', 'C5_SPILL(); macross_geom1_spu_func_000088E0(ctx);')
    body = body.replace('spu_img_restore(ctx, _si); }', 'spu_img_restore(ctx, _si); } C5_RELOAD();')
    rets = body.count('SPU_RET(ctx);')
    body = body.replace('SPU_RET(ctx);', 'C5_SPILL(); SPU_RET(ctx);')
    exits = body.count('{ ctx->pc = ')
    body = body.replace('{ ctx->pc = ', '{ C5_SPILL(); ctx->pc = ')
    assert calls == 2 and exits == 1, (calls, exits)

    decl = '        u128 ' + ', '.join('R%d' % r for r in regs) + ';'
    spill = ' '.join('ctx->gpr[%d] = R%d;' % (r, r) for r in regs)
    reload = ' '.join('R%d = ctx->gpr[%d];' % (r, r) for r in regs)
    prologue = [
        '        /* Generated by tools/build/gen_c5b0_fast.py from the lifted body: SPU',
        '         * registers held in locals, LS accessed directly (big-endian). */',
        decl,
        '        uint8_t* const c5_ls = ctx->ls;',
        '#define C5_SPILL() do { ' + spill + ' } while (0)',
        '#define C5_RELOAD() do { ' + reload + ' } while (0)',
        '#define C5_LSR(a) ({ u128 c5v_; uint32_t c5w_[4]; memcpy(c5w_, c5_ls + ((uint32_t)(a) & 0x3FFF0u), 16); c5v_._u32[0] = __builtin_bswap32(c5w_[0]); c5v_._u32[1] = __builtin_bswap32(c5w_[1]); c5v_._u32[2] = __builtin_bswap32(c5w_[2]); c5v_._u32[3] = __builtin_bswap32(c5w_[3]); c5v_; })',
        '#define C5_LSW(a, v) do { const u128 c5x_ = (v); const uint32_t c5w_[4] = { __builtin_bswap32(c5x_._u32[0]), __builtin_bswap32(c5x_._u32[1]), __builtin_bswap32(c5x_._u32[2]), __builtin_bswap32(c5x_._u32[3]) }; memcpy(c5_ls + ((uint32_t)(a) & 0x3FFF0u), c5w_, 16); } while (0)',
        '        C5_RELOAD();',
    ]
    epilogue = ['#undef C5_SPILL', '#undef C5_RELOAD', '#undef C5_LSR', '#undef C5_LSW']
    new_func = (func[:header_end] + nl + nl.join(prologue) + body + nl.join(epilogue) + nl + '}')

    out = original[:a] + new_func + original[b:]
    SRC.write_text(out, encoding='utf-8', newline='')
    print('rewrote %s: %d registers localized, %d calls, %d exit' % (NAME, len(regs), calls, exits))


if __name__ == '__main__':
    main()
