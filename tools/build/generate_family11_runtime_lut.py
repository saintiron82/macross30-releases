"""Reproduce opt-in runtime family11 LUT sources from validated offline candidate.
No compiler, benchmark, or game execution. --check verifies frozen generated bytes.
"""
from pathlib import Path
import argparse, hashlib, json, sys
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'tools/diag/posttask_gpu_shadow'))
from prepare_family11_dispatch import dispatch_source

def outputs():
 src=ROOT/'tools/diag/posttask_gpu_shadow'
 lut=(src/'family11_cpu_lut.c').read_text()
 assert lut.count('#include "family11_cpu_compact.c"')==1
 lut=lut.replace('#include "family11_cpu_compact.c"', '#include "family11_lut.h"\n#include "../../../vendor/ps3recomp-master/runtime/spu/spu_helpers.h"\n#include <immintrin.h>\n#include <string.h>\nstatic inline __m128i f11_bytes(const unsigned char*p){unsigned v;memcpy(&v,p,4);return _mm_cvtepu8_epi32(_mm_cvtsi32_si128((int)v));}')
 lut=lut.replace('#include "../../vendor/', '#include "../../../vendor/')
 lut=lut.replace(' if(!f11_lut_contract(c,abi))return 0;', ' if(g_spu_ls_watch_n!=0||g_spu_smc_watch!=0)return 0;\n if(!f11_lut_contract(c,abi))return 0;')
 old='int macross_posttask_f11_first88_try(spu_context*c,const uint32_t*abi,uint32_t current_sp){if(current_sp!=c->gpr[1]._u32[0])return 0;return macross_f11_lut_first88_abi(c,abi);}'
 assert lut.count(old)==1
 lut=lut.replace(old, '''int macross_posttask_f11_first88_try(spu_context*c,const uint32_t*abi,uint32_t current_sp){
 static SPU_THREAD_LOCAL unsigned logged;
 int accepted=current_sp==c->gpr[1]._u32[0]&&macross_f11_lut_first88_abi(c,abi);
 unsigned bit=accepted?1u:2u;
 if(!(logged&bit)){logged|=bit;fprintf(stderr,"[posttask-f11-lut] selected=%d dst=%05X a=%05X b=%05X width=%u strides=%u,%u thread=%lu\\n",accepted,abi[0],abi[1],abi[2],abi[5],abi[3],abi[4],(unsigned long)GetCurrentThreadId());}
 return accepted;
}''')
 lut=lut.replace('/* Isolated exact scale1 candidate. Not selected by the game runtime yet.', '/* Generated runtime opt-in scale1 candidate; regenerate with tools/build/generate_family11_runtime_lut.py.')
 header='''/* Generated; opt-in AVX2-only runtime family11 LUT. */
#ifndef MACROSS_FAMILY11_LUT_H
#define MACROSS_FAMILY11_LUT_H
#include "../../../vendor/ps3recomp-master/runtime/spu/spu_context.h"
void macross_posttask_f11_dispatch_6914(spu_context*ctx);
int macross_posttask_f11_first88_try(spu_context*,const uint32_t*,uint32_t);
#endif
'''
 outer='/* Generated from original family11 outer; retain original last row pair/state. */\n#include "family11_lut.h"\n#include "family11.h"\n#include "../../../vendor/ps3recomp-master/runtime/spu/spu_helpers.h"\n#include <string.h>\n'+dispatch_source()
 return {'family11_lut.c':lut,'family11_lut_contract.h':(src/'family11_lut_contract.h').read_text(),'family11_lut.h':header,'family11_lut_outer.c':outer}
if __name__=='__main__':
 ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args();dst=ROOT/'native/macross30/spu_posttask_native';files=outputs()
 for name,text in files.items():
  p=dst/name
  if a.check:
   if not p.exists() or p.read_text()!=text:raise SystemExit('stale: '+str(p))
  else:p.write_text(text,encoding='utf-8')
 print(json.dumps({n:hashlib.sha256(t.encode()).hexdigest() for n,t in files.items()},indent=2))
